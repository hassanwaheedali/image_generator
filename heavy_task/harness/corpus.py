def _h(text: str) -> int:
    return int(hashlib.sha256(text.encode()).hexdigest()[:8], 16)


def group_split(examples: list[Example], *, salt: str = "heaviest-v1", eval_every: int = 5) -> tuple[list[Example], list[Example]]:
    """**Leakage-safe** split: whole model-code *groups* go to one side.

    ``eval_every=5`` is a 20% eval split by group, not by row.
    """
    train: list[Example] = []
    held: list[Example] = []
    for ex in examples:
        (held if _h(f"{salt}\x1f{ex.group}") % eval_every == 0 else train).append(ex)
    return train, held


def leaky_split(examples: list[Example], *, eval_every: int = 5) -> tuple[list[Example], list[Example]]:
    """Naive row-wise split - kept so the grader can *demonstrate* the inflation.

    Near-duplicate titles (same code, same shop) straddle the boundary, so a policy
    that memorised the row's phrasing looks precise on eval and is not.
    """
    train: list[Example] = []
    held: list[Example] = []
    for ex in examples:
        (held if _h(ex.id) % eval_every == 0 else train).append(ex)
    return train, held


