"""Labelled (row, page) corpus mined from the *real* catalogue in this repo.

Part of the heaviest-task harness.  Pure stdlib + the pipeline's own pure matcher
modules, so it runs anywhere the repo's tests run - no Pillow, no network.

The corpus is the ground truth for the graded gates, so **do not edit this file to
make a gate pass**; the grader re-derives the matcher's facts itself (see
:func:`score_of`) and only the *policy* under test comes from your module.

Mining is fully deterministic: sorted iteration, no RNG, a stable id per example.
Each pair is emitted in both directions (row=a/page=b and row=b/page=a), which is
what catches asymmetric policies.

Label semantics (and their honest weakness - see BRIEF Part B):

* ``True``  - the two titles name the same product (same model code, no positive
  colour/series contradiction), seen through one of six shop-style renderings.
* ``False`` - the page names a *different* product that is superficially close:
  ``colour`` (same code, conflicting colourway), ``series`` (same code, the page
  names a line the row does not and vice-versa), ``code`` (same brand + capacity,
  different digit skeleton).
"""

