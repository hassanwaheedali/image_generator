def _titles(path: Path) -> list[tuple[str, str]]:
    """Distinct ``(title, brand)`` in sheet order, deduplicated on title."""
    out: list[tuple[str, str]] = []
    seen: set[str] = set()
    csv.field_size_limit(10**9)
    with path.open(newline="", encoding="utf-8-sig") as handle:
        for row in csv.DictReader(handle):
            title = (row.get("Title") or "").strip()
            brand = (row.get("Brand") or "").strip()
            if not title or title in seen:
                continue
            seen.add(title)
            out.append((title, brand))
    return out


def _code(title: str) -> str:
    keys = _keys(title)  # type: ignore[assignment]
    tokens = tuple(getattr(keys, "tokens", ()))  # type: ignore[attr-defined]
    return tokens[0].lower() if tokens else ""


def _colour(title: str) -> str:
    keys = _keys(title)  # type: ignore[assignment]
    return str(getattr(keys, "colour_word", "") or "")  # type: ignore[attr-defined]


def _name_words(title: str) -> tuple[str, ...]:
    keys = _keys(title)  # type: ignore[assignment]
    return tuple(getattr(keys, "name_words", ()))  # type: ignore[attr-defined]


def _facts(title: str) -> tuple[tuple[str, str], ...]:
    keys = _keys(title)  # type: ignore[assignment]
    return tuple(getattr(keys, "variant_facts", ()))  # type: ignore[attr-defined]


def _disjoint(one: tuple[str, ...], other: tuple[str, ...]) -> bool:
    """No word on either side resembles a word on the other (both sides non-empty)."""
    return bool(one) and bool(other) and not any(w in o for w in one for o in other)


def build_corpus(path: Path = PRODUCTS_CSV, *, max_per_group: int = 6, cross_negatives: int = 240) -> list[Example]:
    """Mine same-code positives and near-miss negatives out of the real catalogue."""
    titles = _titles(path)
    by_group: dict[str, list[tuple[str, str]]] = defaultdict(list)
    for title, brand in titles:
        code = _code(title)
        if code:
            by_group[code].append((title, brand))

    examples: list[Example] = []
    counter = 0

    def emit(row: str, row_brand: str, other: str, other_brand: str, kind: str, label: bool, control: bool) -> None:
        nonlocal counter
        mode = counter % 6
        counter += 1
        page = render_page(other, other_brand, mode)
        examples.append(
            Example(
                id=Example.make_id(row, page, kind),
                row_title=row,
                row_brand=row_brand,
                page_text=page,
                label=label,
                kind=kind,
                group=_code(row) or "misc",
                control=control,
                mode=mode,
            )
        )

    for group in sorted(by_group):
        members = sorted(by_group[group])[:max_per_group]
        for i in range(len(members)):
            for j in range(i + 1, len(members)):
                (ta, ba), (tb, bb) = members[i], members[j]
                ca, cb = _colour(ta), _colour(tb)
                control = True
                if ca and cb and ca != cb:
                    kind, label, control = "colour", False, False
                elif _disjoint(_name_words(ta), _name_words(tb)):
                    kind, label, control = "series", False, False
                elif ca and not cb:
                    kind, label = "one_sided_colour", True
                else:
                    kind, label = "reword", True
                emit(ta, ba, tb, bb, kind, label, control)
                emit(tb, bb, ta, ba, kind, label, control)

    # cross-group near-misses: same brand and capacity, different digit skeleton.
    by_brand: dict[str, list[tuple[str, str]]] = defaultdict(list)
    for group in sorted(by_group):
        for title, brand in sorted(by_group[group])[:2]:
            if brand:
                by_brand[brand.lower()].append((title, brand))
    emitted = 0
    for brand in sorted(by_brand):
        pool = by_brand[brand]
        for i in range(len(pool)):
            for j in range(i + 1, len(pool)):
                if emitted >= cross_negatives:
                    break
                ta, _ = pool[i]
                tb, _ = pool[j]
                ca, cb = _code(ta), _code(tb)
                if not ca or ca == cb:
                    continue
                if numeric_stem(ca) == numeric_stem(cb) or not numeric_stem(ca):
                    continue
                if _facts(ta) != _facts(tb):
                    continue
                emit(ta, brand, tb, brand, "code", False, False)
                emit(tb, brand, ta, brand, "code", False, False)
                emitted += 2
            if emitted >= cross_negatives:
                break
        if emitted >= cross_negatives:
            break

    examples.sort(key=lambda ex: ex.id)
    return examples


